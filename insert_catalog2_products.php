$stmt = $pdo->prepare("INSERT INTO products (name, price, oldPrice, rating, reviews, img, description, specs, category, icon, catalog_id) 
                       VALUES (:name, :price, :oldPrice, :rating, :reviews, :img, :description, :specs, :category, :icon, :catalog_id)");

$totalInserted = 0;
foreach ($rawCatalogData as $categoryItem) {
    $categoryName = $categoryItem['category'];
    $categoryIcon = $categoryItem['icon'];
    
    foreach ($categoryItem['items'] as $product) {
        // Если поле img пусто, генерируем простое имя файла-заглушки (вы должны заменить это на реальные пути к изображениям)
        if (empty($product['img'])) {
            $product['img'] = strtolower(str_replace([' ', 'ё', 'й', 'ц', 'у', 'к', 'е', 'н', 'г', 'ш', 'щ', 'з', 'х', 'ъ', 'ф', 'ы', 'в', 'а', 'п', 'р', 'о', 'л', 'д', 'ж', 'э', 'я', 'ч', 'с', 'м', 'и', 'т', 'ь', 'б', 'ю'], ['_', 'yo', 'iy', 'ts', 'u', 'k', 'e', 'n', 'g', 'sh', 'sch', 'z', 'h', 'zz', 'f', 'y', 'v', 'a', 'p', 'r', 'o', 'l', 'd', 'zh', 'e', 'ya', 'ch', 's', 'm', 'i', 't', 'mm', 'b', 'yu'], $product['name'])) . '.jpg';
        }

        try {
            $stmt->execute([
                ':name' => $product['name'],
                ':price' => $product['price'],
                ':oldPrice' => $product['oldPrice'],
                ':rating' => $product['rating'],
                ':reviews' => $product['reviews'],
                ':img' => $product['img'],
                ':description' => $product['desc'],
                ':specs' => json_encode($product['specs'], JSON_UNESCAPED_UNICODE), // Храним specs как JSON
                ':category' => $categoryName,
                ':icon' => $categoryIcon,
                ':catalog_id' => $catalogId
            ]);
            $totalInserted++;
        } catch (\PDOException $e) {
            echo "Ошибка при вставке товара " . $product['name'] . ": " . $e->getMessage() . "\n";
        }
    }
}

